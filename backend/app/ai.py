from .auth import get_current_user

router = APIRouter(prefix="/ai", tags=["ai"])

# === SCHEMAS ===

class BioRequest(BaseModel):
    keywords: List[str]
    category: str
    experience_level: str

class BioResponse(BaseModel):
    bio: str

class JobDescriptionRequest(BaseModel):
    title: str
    category: str
    keywords: List[str]

class JobDescriptionResponse(BaseModel):
    description: str

class MatchResponse(BaseModel):
    matches: List[dict] # simplified worker info

# === AI LOGIC ===

GROQ_URL = "https://api.groq.com/openai/v1/chat/completions"
GROQ_MODEL = "llama-3.3-70b-versatile"


def _mock_ai_generate(prompt: str) -> str:
    """Fallback used only when GROQ_API_KEY is unset or the API call fails."""
    return f"[AI Generated Content based on: {prompt[:50]}...] This is a professional description generated by AI."


async def _call_groq(prompt: str, *, max_tokens: int = 200) -> str:
    if not settings.groq_api_key:
        return _mock_ai_generate(prompt)

    try:
        async with httpx.AsyncClient(timeout=20.0) as client:
            response = await client.post(
                GROQ_URL,
                headers={"Authorization": f"Bearer {settings.groq_api_key}"},
                json={
                    "model": GROQ_MODEL,
                    "messages": [
                        {
                            "role": "system",
                            "content": (
                                "You write concise, professional marketplace copy for "
                                "5edma.tn, a Tunisian services marketplace. Respond with "
                                "only the requested text, no preamble or quotation marks."
                            ),
                        },
                        {"role": "user", "content": prompt},
                    ],
                    "max_tokens": max_tokens,
                    "temperature": 0.7,
                },
            )
            response.raise_for_status()
            data = response.json()
            return data["choices"][0]["message"]["content"].strip()
    except (httpx.HTTPError, KeyError, IndexError) as e:
        print(f"Groq AI error: {e}")
        return _mock_ai_generate(prompt)

# === ENDPOINTS ===

@router.post("/generate-bio", response_model=BioResponse)
async def generate_bio(req: BioRequest):
    prompt = f"Write a professional bio for a {req.category} worker with {req.experience_level} experience. Keywords: {', '.join(req.keywords)}."
    bio = await _call_groq(prompt)
    return BioResponse(bio=bio)

@router.post("/generate-job-description", response_model=JobDescriptionResponse)
async def generate_job_description(req: JobDescriptionRequest):
    prompt = f"Write a detailed job description for a job titled '{req.title}' in category '{req.category}'. Requirements: {', '.join(req.keywords)}."
    description = await _call_groq(prompt, max_tokens=300)
    return JobDescriptionResponse(description=description)

@router.post("/match-workers/{job_id}", response_model=MatchResponse)
async def match_workers(
    job_id: int,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    # 1. Get Job
    job = await db.get(JobOffer, job_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")

    # 2. Find workers with matching category
    # Simple matching logic: same category
    query = select(User).join(WorkerProfile).options(selectinload(User.worker_profile))
    query = query.where(WorkerProfile.categories.contains([job.category]))
    
    # Filter by location if needed (simple string match)
    if job.location:
         query = query.where(WorkerProfile.location.ilike(f"%{job.location}%"))

    result = await db.execute(query)
    workers = result.scalars().all()

    matches = []
    for worker in workers:
        matches.append({
            "worker_id": worker.id,
            "name": worker.email, # Use name if available in profile
            "match_score": 0.85, # Mock score
            "skills": worker.worker_profile.categories
        })
    
    return MatchResponse(matches=matches)
